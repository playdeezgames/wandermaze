ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEET = os.path.join(ROOT, "tools", "data", "urizen_onebit_tileset__v2d0.png")
OUT = os.path.join(ROOT, "src", "game", "assets.odin")

