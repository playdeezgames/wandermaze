"""Generate src/game/assets.odin from the Urizen 1-bit tileset (CC0, vurmux) plus two hand-drawn icons.

Usage: python3 -I tools/extract_assets.py [--png OUT.png]   (needs Pillow)
--png writes a preview of the icons (in game colours) and a font sample.
"""
