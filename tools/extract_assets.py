# Urizen bitmap font: row start (all at column 78), characters in order.
FONT_ROWS = [
    (44, "ABCDEFGHIJKLMNOPQRST12345"),
    (45, "UVWXYZabcdefghijklmn67890"),
    (46, "opqrstuvwxyz()[]{}<>+-?!^"),
    (47, ":#_@%~$\"'&*=`|/\\.,;"),
]


def tile(sheet, col, row):
    return sheet.crop((13 * col + 1, 13 * row + 1, 13 * col + 13, 13 * row + 13))


def mask_of(img):
    return [1 if sum(img.getpixel((x, y))[:3]) > 60 else 0 for y in range(12) for x in range(12)]


def art(text, colour, accent):
    rows = [r for r in text.strip().split("\n")]
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), "icon art must be 12x12"
    return [{".": 0, "#": 1, "o": 2}[ch] for r in rows for ch in r]


def build():
    sheet = Image.open(SHEET).convert("RGB")
    icons = []  # (name, pixels, main colour, accent colour)
    for name, (c, r), colour in TILES:
        icons.append((name, mask_of(tile(sheet, c, r)), colour, colour))
    for i, (text, main, accent) in enumerate(FIRE_FRAMES):
        icons.append(("Fire" if i == 0 else "Fire_%d" % i, art(text, main, accent), main, accent))
    icons.append(("Drop", art(DROP[0], DROP[1], DROP[2]), DROP[1], DROP[2]))
    font = [[0] * 12 for _ in range(128)]
    for row, chars in FONT_ROWS:
        for i, ch in enumerate(chars):
            m = mask_of(tile(sheet, 78 + i, row))
            font[ord(ch)] = [sum(m[y * 12 + x] << x for x in range(12)) for y in range(12)]
    return icons, font


def odin_source(icons, font):
    o = ["// Generated by tools/extract_assets.py. Do not edit.",
         "// Icons and font: Urizen 1-bit tileset by vurmux (CC0), https://vurmux.itch.io/urizen-onebit-tileset;",
         "// the flame and the droplet are hand-drawn in the same style.", "package game", ""]
    o.append("// 0xRRGGBB")
    o.append("PALETTE := [16]u32{")
    o += ["\t0x%s," % c for c in PALETTE]
    o += ["}", ""]
    o.append("Icon :: enum {")
    o += ["\t%s," % n for n, *_ in icons]
    o += ["}", ""]
    o.append("// Row-major 12x12: 0 transparent, 1 main colour, 2 accent colour.")
    o.append("ICONS := [Icon][144]u8{")
    for n, px, _, _ in icons:
        o.append("\t.%s = {%s}," % (n, ", ".join(map(str, px))))
    o += ["}", ""]
    o.append("ICON_COLORS := [Icon][2]u8{")
    for n, _, main, accent in icons:
        o.append("\t.%s = {%d, %d}," % (n, main, accent))
    o += ["}", ""]
    o.append("// Urizen font: 12 scanlines per ASCII character, bit x is pixel x (least significant bit leftmost).")
    o.append("FONT := [128][12]u16{")
    for g in font:
        o.append("\t{" + ", ".join("0x%03x" % v for v in g) + "},")
    o += ["}", ""]
    return "\n".join(o)


def preview(path, icons, font, s=6):
    pal = [tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) for h in PALETTE]
    text = "LEVEL 1 ALIVE Score: 0123456789 Protection: DEAD!"
    w = 12 * len(icons) + 4
    img = Image.new("RGB", (max(w, 6 * 0 + 8 * len(text)), 12 + 4 + 14), pal[0])
    for i, (n, px, main, accent) in enumerate(icons):
        for j, p in enumerate(px):
            if p:
                img.putpixel((i * 12 + j % 12 + 2, j // 12 + 1), pal[main if p == 1 else accent])
    x = 2
    for ch in text:
        rows = font[ord(ch)]
        used = 0
        for r in rows:
            used |= r
        if not used:
            x += 4
            continue
        lo = (used & -used).bit_length() - 1
        hi = used.bit_length()
        for y, r in enumerate(rows):
            for b in range(lo, hi):
                if r >> b & 1 and x + b - lo < img.width:
                    img.putpixel((x + b - lo, 16 + y), pal[5])
        x += hi - lo + 1
    img.resize((img.width * s, img.height * s), Image.NEAREST).save(path)


def main():
    icons, font = build()
    open(OUT, "w").write(odin_source(icons, font))
    print("wrote", OUT, "(%d icons)" % len(icons))
    if "--png" in sys.argv:
        preview(sys.argv[sys.argv.index("--png") + 1], icons, font)


main()
