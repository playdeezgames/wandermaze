#!/usr/bin/env python3
"""Extract the sprites, palette and font from wandermaze.tic into src/game/assets.odin.

Usage: python3 -I tools/extract_cart.py [--png OUT.png]
Stdlib only. --png writes a contact sheet (sprites + sample text) for eyeballing.
"""
import os, re, struct, sys, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CART = os.path.join(ROOT, "wandermaze.tic")
FONT = os.path.join(ROOT, "tools", "data", "font.inl")
OUT = os.path.join(ROOT, "src", "game", "assets.odin")

CHUNK_TILES = 1
# The cart has no palette chunk, so TIC-80 uses its default palette (Sweetie-16).
SWEETIE16 = [
    "1a1c2c", "5d275d", "b13e53", "ef7d57", "ffcd75", "a7f070", "38b764", "257179",
    "29366f", "3b5dc9", "41a6f6", "73eff7", "f4f4f4", "94b0c2", "566c86", "333c57",
]


def chunks(data):
    i = 0
    while i < len(data):
        kind, size = data[i] & 31, data[i + 1] | data[i + 2] << 8
        yield kind, data[i + 4:i + 4 + size]
        i += 4 + size


def read_tiles(data):
    """Each tile is 32 bytes: 8 rows of 4 bytes, 4bpp, low nibble is the left pixel."""
    for kind, body in chunks(data):
        if kind == CHUNK_TILES:
            return [[(body[t * 32 + y * 4 + x // 2] >> (4 * (x & 1))) & 15
                     for y in range(8) for x in range(8)] for t in range(len(body) // 32)]
    raise SystemExit("no tiles chunk")


def read_font(path):
    values = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", open(path).read())]
    glyphs = [values[c * 8:c * 8 + 8] for c in range(len(values) // 8)]
    glyphs += [[0] * 8] * (128 - len(glyphs))
    return glyphs


def odin_source(tiles, font):
    o = ["// Generated by tools/extract_cart.py from wandermaze.tic. Do not edit.", "package game", ""]
    o.append("// TIC-80 default palette (Sweetie-16), as 0xRRGGBB.")
    o.append("PALETTE := [16]u32{")
    o += ["\t0x%s," % c for c in SWEETIE16]
    o += ["}", ""]
    o.append("// Palette indices, row-major 8x8. Index n is the sprite for Cell n (0 is blank).")
    o.append("SPRITES := [%d][64]u8{" % len(tiles))
    for t in tiles:
        o.append("\t{" + ", ".join(str(p) for p in t) + "},")
    o += ["}", ""]
    o.append("// TIC-80 built-in font: 8 scanlines per ASCII character, least significant bit is the leftmost pixel.")
    o.append("FONT := [128][8]u8{")
    for g in font:
        o.append("\t{" + ", ".join("0x%02x" % b for b in g) + "},")
    o += ["}", ""]
    return "\n".join(o)


def write_png(path, w, h, rgb):
    raw = b"".join(b"\0" + bytes(rgb[y * w * 3:(y + 1) * w * 3]) for y in range(h))
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d))
    open(path, "wb").write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                           + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def contact_sheet(path, tiles, font, scale=8):
    text = "Status: ALIVE DEAD! Left: Score: Protection: Level: 0123456789"
    w, h = 6 * len(text) + 2, 8 + 2 + 8
    img = [[(0, 0, 0)] * w for _ in range(h)]
    pal = [tuple(int(c[i:i + 2], 16) for i in (0, 2, 4)) for c in SWEETIE16]
    for t, tile in enumerate(tiles):
        for i, p in enumerate(tile):
            img[i // 8][t * 8 + i % 8] = pal[p] if t else (40, 40, 40)
    x = 1
    for ch in text:  # fixed 6px advance: just for eyeballing the glyphs
        for y, row in enumerate(font[ord(ch)]):
            for b in range(6):
                if row >> b & 1 and x + b < w:
                    img[10 + y][x + b] = (255, 255, 255)
        x += 6
    big = []
    for y in range(h):
        line = [v for px in img[y] for _ in range(scale) for v in px]
        big += line * scale
    write_png(path, w * scale, h * scale, big)


def main():
    tiles = read_tiles(open(CART, "rb").read())
    font = read_font(FONT)
    open(OUT, "w").write(odin_source(tiles, font))
    print("wrote", OUT, "(%d sprites, %d glyphs)" % (len(tiles), len(font)))
    if "--png" in sys.argv:
        contact_sheet(sys.argv[sys.argv.index("--png") + 1], tiles, font)


main()
